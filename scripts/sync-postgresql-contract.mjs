import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const checkOnly = process.argv.includes('--check');
const sourceSchemaPath = path.join(root, 'prisma', 'schema.prisma');
const targetSchemaPath = path.join(root, 'prisma', 'postgresql', 'schema.prisma');
const migrationsPath = path.join(root, 'prisma', 'postgresql', 'migrations');
const baselinePath = path.join(migrationsPath, '00000000000000_baseline', 'migration.sql');
const lockPath = path.join(migrationsPath, 'migration_lock.toml');
const prismaCliPath = path.join(root, 'node_modules', 'prisma', 'build', 'index.js');
const contractDatabaseUrl =
  'postgresql://contract:contract@127.0.0.1:5432/mandyal_contract?schema=public';
const expectedLock = `# Please do not edit this file manually
# It should be added in your version-control system (i.e. Git)
provider = "postgresql"
`;

function normalize(value) {
  return value.replace(/\r\n/g, '\n').trimEnd() + '\n';
}

function fail(message) {
  console.error(`PostgreSQL contract verification failed: ${message}`);
  process.exit(1);
}

function materializeSchema(source) {
  const normalized = normalize(source);
  const outputMatches = normalized.match(/output\s+=\s+"\.\.\/generated\/prisma"/g) ?? [];
  const providerMatches = normalized.match(/provider\s+=\s+"sqlite"/g) ?? [];
  if (outputMatches.length !== 1 || providerMatches.length !== 1) {
    fail('the SQLite source schema no longer has the expected generator and datasource contract.');
  }

  return normalized
    .replace(
      /output\s+=\s+"\.\.\/generated\/prisma"/,
      'output   = "../../generated/prisma-postgresql"',
    )
    .replace(/provider\s+=\s+"sqlite"/, 'provider = "postgresql"');
}

function runPrisma(args) {
  if (!fs.existsSync(prismaCliPath)) fail('Prisma CLI is not installed; run npm ci first.');
  const result = spawnSync(process.execPath, [prismaCliPath, ...args], {
    cwd: root,
    encoding: 'utf8',
    env: {
      ...process.env,
      DATABASE_URL: contractDatabaseUrl,
      JITI_CACHE: 'false',
      JITI_FS_CACHE: 'false',
    },
    maxBuffer: 16 * 1024 * 1024,
  });
  if (result.status !== 0) {
    const detail = normalize(`${result.stdout ?? ''}\n${result.stderr ?? ''}`).trim();
    fail(`Prisma ${args.join(' ')} failed.\n${detail}`);
  }
  return normalize(result.stdout ?? '');
}

function compareFile(filePath, expected, label) {
  if (!fs.existsSync(filePath)) fail(`${label} is missing; run npm run db:sync:postgresql.`);
  if (normalize(fs.readFileSync(filePath, 'utf8')) !== normalize(expected)) {
    fail(`${label} is stale; run npm run db:sync:postgresql and review the generated change.`);
  }
}

const sourceSchema = fs.readFileSync(sourceSchemaPath, 'utf8');
const postgresqlSchema = materializeSchema(sourceSchema);

if (!checkOnly) {
  fs.mkdirSync(path.dirname(targetSchemaPath), { recursive: true });
  fs.writeFileSync(targetSchemaPath, postgresqlSchema);
} else {
  compareFile(targetSchemaPath, postgresqlSchema, 'PostgreSQL Prisma schema');
}

runPrisma(['validate', '--schema', targetSchemaPath]);
runPrisma(['generate', '--schema', targetSchemaPath]);
const baseline = runPrisma([
  'migrate',
  'diff',
  '--from-empty',
  '--to-schema',
  targetSchemaPath,
  '--script',
]);

if (!baseline.includes('CREATE TABLE'))
  fail('the generated PostgreSQL baseline contains no tables.');
if (/AUTOINCREMENT|PRAGMA|WITHOUT ROWID/i.test(baseline)) {
  fail('the generated baseline contains SQLite-specific SQL.');
}

const modelCount = (sourceSchema.match(/^model\s+\w+\s*\{/gm) ?? []).length;
const tableCount = (baseline.match(/^CREATE TABLE /gm) ?? []).length;
if (modelCount !== tableCount) {
  fail(
    `model/table parity failed: ${modelCount} Prisma models but ${tableCount} PostgreSQL tables.`,
  );
}

if (checkOnly) {
  compareFile(baselinePath, baseline, 'PostgreSQL baseline migration');
  compareFile(lockPath, expectedLock, 'PostgreSQL migration lock');
} else {
  fs.mkdirSync(path.dirname(baselinePath), { recursive: true });
  fs.writeFileSync(baselinePath, baseline);
  fs.writeFileSync(lockPath, expectedLock);
}

console.log(
  `${checkOnly ? 'Verified' : 'Synchronized'} PostgreSQL schema parity and a ${tableCount}-table native baseline without connecting to a database.`,
);
